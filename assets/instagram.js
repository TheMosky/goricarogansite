/* ============================================================
   Instagram "Naši radovi" — self-hosted feed
   Reads local assets/instagram.json (generated by a GitHub Action).
   Renders posts into the gallery in the existing .ga style.
   Falls back to the static markup already in the HTML if the feed
   is missing / empty / errors. No tokens, no third-party, no CORS.
   ============================================================ */
(function () {
  'use strict';
  var grid = document.querySelector('#galerija .gallery__grid');
  if (!grid || !('fetch' in window)) return;

  var MAX = 8;
  var reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  var PROFILE = 'https://www.instagram.com/dr_gorica_rogan_opacic/';

  function shortCap(caption, timestamp) {
    var c = (caption || '').trim().replace(/\s+/g, ' ');
    if (c) {
      c = c.split(/[.\n!?#]/)[0].trim();
      if (c.length > 42) c = c.slice(0, 40).trim() + '…';
      if (c) return c;
    }
    if (timestamp) {
      try {
        return new Date(timestamp).toLocaleDateString('sr-RS', { day: '2-digit', month: 'long', year: 'numeric' });
      } catch (e) {}
    }
    return 'Poliklinika Pekić';
  }

  fetch('assets/instagram.json', { cache: 'no-cache' })
    .then(function (r) { if (!r.ok) throw 0; return r.json(); })
    .then(function (data) {
      var posts = Array.isArray(data) ? data : (data && data.posts) || [];
      posts = posts.filter(function (p) { return p && p.image; }).slice(0, MAX);
      if (!posts.length) return; // keep static fallback

      var frag = document.createDocumentFragment();
      posts.forEach(function (p) {
        var cap = shortCap(p.caption, p.timestamp);
        var fig = document.createElement('figure');
        fig.className = 'ga';

        var img = document.createElement('img');
        img.src = p.image;
        img.loading = 'lazy';
        img.alt = cap || 'Rad — Poliklinika Pekić';
        img.onerror = function () { fig.style.display = 'none'; };

        var figc = document.createElement('figcaption');
        figc.className = 'ga__cap mono';
        figc.textContent = cap;

        var a = document.createElement('a');
        a.className = 'ga__lnk';
        a.href = p.permalink || PROFILE;
        a.target = '_blank';
        a.rel = 'noopener';
        a.setAttribute('aria-label', 'Otvori objavu na Instagramu');
        a.setAttribute('data-cursor', 'view');

        fig.appendChild(img);
        fig.appendChild(figc);
        fig.appendChild(a);
        frag.appendChild(fig);
      });

      grid.innerHTML = '';
      grid.appendChild(frag);

      var tiles = Array.prototype.slice.call(grid.querySelectorAll('.ga'));
      if (reduce || !('IntersectionObserver' in window)) {
        tiles.forEach(function (t) { t.classList.add('is-in'); });
      } else {
        var io = new IntersectionObserver(function (es, o) {
          es.forEach(function (e) { if (e.isIntersecting) { e.target.classList.add('is-in'); o.unobserve(e.target); } });
        }, { threshold: 0.12, rootMargin: '0px 0px -6% 0px' });
        tiles.forEach(function (t) { io.observe(t); });
      }
    })
    .catch(function () { /* keep static fallback silently */ });
})();
